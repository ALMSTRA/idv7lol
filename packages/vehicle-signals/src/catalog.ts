import type { UnitId } from './units.js';

/**
 * How confident we are that a signal exists and is correct on a given head unit.
 *
 * - `core`: present on every iDrive 7 MGU car; safe to require.
 * - `common`: present on most cars but may be missing on some engines/markets.
 * - `model-dependent`: only on some drivetrains (turbo, hybrid, xDrive…).
 * - `experimental`: observed but not verified on real hardware by this project.
 */
export type Availability = 'core' | 'common' | 'model-dependent' | 'experimental';

export type SignalKind = 'number' | 'boolean' | 'enum' | 'string';

export interface SignalDef {
  /** Stable identifier used in themes, e.g. "engine.rpm". */
  id: string;
  /** Human-readable English name. */
  name: string;
  /** Group used by the Studio inspector, e.g. "Engine". */
  group: SignalGroup;
  kind: SignalKind;
  /** Canonical unit the value is stored in. */
  unit: UnitId;
  /** Expected range; used to validate component bindings and drive the simulator. */
  min: number;
  max: number;
  /** Decimals recommended for display. */
  decimals: number;
  /** For enum signals, the allowed values in order. */
  enumValues?: readonly string[];
  availability: Availability;
  /** Typical update rate on the head unit, in Hz (0 = static / on change). */
  rateHz: number;
  description: string;
}

export type SignalGroup =
  | 'Vehicle'
  | 'Engine'
  | 'Transmission'
  | 'Fuel'
  | 'Temperatures'
  | 'Pressures'
  | 'Electrical'
  | 'Hybrid'
  | 'Chassis'
  | 'Driver'
  | 'Lighting'
  | 'Environment'
  | 'Time'
  | 'System';

const S = (def: SignalDef): SignalDef => def;

