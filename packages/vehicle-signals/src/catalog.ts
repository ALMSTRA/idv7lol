const BY_ID: ReadonlyMap<string, SignalDef> = new Map(SIGNALS.map((s) => [s.id, s]));

export function getSignal(id: string): SignalDef | undefined {
  return BY_ID.get(id);
}

export function hasSignal(id: string): boolean {
  return BY_ID.has(id);
}

export function signalsByGroup(): Map<SignalGroup, SignalDef[]> {
  const m = new Map<SignalGroup, SignalDef[]>();
  for (const s of SIGNALS) {
    const list = m.get(s.group) ?? [];
    list.push(s);
    m.set(s.group, list);
  }
  return m;
}

export const SIGNAL_IDS: readonly string[] = SIGNALS.map((s) => s.id);
