/**
 * Compiles the themes the car app carries (BUNDLED, below) into the idv7lol MGU app.
 *
 *   npx tsx tools/build/build-mgu-themes.ts
 *
 * The app kit ships only top-level files, so each theme becomes
 * apps/idv7lol/theme_<id>.js (a CommonJS module with the compiled theme) and
 * each font family apps/idv7lol/font_<family>.wad (R8 atlas) plus
 * font_<family>.js (metrics). themes_index.js lists them and app.json's
 * "clusterTheme" and "palette" settings are refreshed from the result.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { compileThemeFile } from '../../packages/theme-compiler/src/node.js';
import type { CompiledTheme } from '../../packages/theme-compiler/src/types.js';
import { SHADERS } from '../../packages/theme-compiler/src/glsl.js';

const APP = 'apps/idv7lol';
/**
 * The themes the car app carries, as folders under themes/, in the order its list shows them.
 * Every other theme reaches the car from the Studio or the site, on a USB stick.
 */
const BUNDLED = [
  'giallo',
  'lily-pad',
  'map-view',
  'modern',
  'neon-drive',
  'night-minimal',
  'supercar-track',
  'vdo-classic-m',
  'community/analog-sport',
  'community/classic-m-cluster',
  'community/ct-aero',
  'community/ct-apex',
  'community/ct-circuit',
  'community/ct-veloce',
  'community/ct-vetro',
  'community/digital-dash',
  'community/gt3',
  'community/kb-live',
  'community/kb-neon',
];
/** The theme a new install starts with. */
const DEFAULT_THEME = 'idv7lol-modern';
const THEME_DIRS = BUNDLED.filter((d) => {
  const there = existsSync(join('themes', d, 'theme.json'));
  if (!there) console.error(`FAIL themes/${d}: no theme.json`);
  return there;
});
if (THEME_DIRS.length !== BUNDLED.length) process.exitCode = 1;
/** What this build writes, so that what an earlier one left of a theme no longer carried goes. */
const written = new Set<string>();

const index: Array<{ id: string; name: string; module: string; palettes: string[] }> = [];
const fonts = new Set<string>();
let failed = false;

for (const dir of THEME_DIRS) {
  const file = join('themes', dir, 'theme.json');
  const result = compileThemeFile(file);
  if (!result.compiled) {
    failed = true;
    console.error(`FAIL ${file}: ${result.report.errors.map((e) => e.message).join('; ')}`);
    continue;
  }
  const c: CompiledTheme = result.compiled;
  const slug = c.id.replace(/[^a-z0-9]+/g, '_');
  const module = `theme_${slug}`;
  // The kit ships top-level files only: each baked image becomes <theme>_<component>.wad.
  const imagesByPath = new Map<string, string>();
  for (const img of c.images) {
    const wad = `${slug}_${img.componentId.replace(/[^a-z0-9]+/g, '_')}.wad`;
    imagesByPath.set(img.file, wad);
    img.file = wad;
  }
  // and each picture a layer samples (a custom icon, a needle of your own) <theme>_<layer>.wad
  for (const p of c.pieces) {
    if (!p.texture) continue;
    const wad = `${slug}_${p.key.replace(/[^a-z0-9]+/gi, '_').toLowerCase()}.wad`;
    imagesByPath.set(p.texture.file, wad);
    p.texture.file = wad;
  }
  writeFileSync(
    join(APP, `${module}.js`),
    `'use strict';\n/* Generated by tools/build/build-mgu-themes.ts from ${file.replace(/\\/g, '/')}. Do not edit. */\nmodule.exports = ${JSON.stringify(c)};\n`,
  );
  written.add(`${module}.js`);
  for (const f of result.files) {
    if (f.path.startsWith('fonts/') && f.path.endsWith('.r8')) {
      const fam = f.path.slice(6, -3);
      fonts.add(fam);
      writeFileSync(join(APP, `font_${fam}.wad`), f.data as Uint8Array);
    } else if (f.path.startsWith('fonts/') && f.path.endsWith('.json')) {
      const fam = f.path.slice(6, -5);
      writeFileSync(
        join(APP, `font_${fam}.js`),
        `'use strict';\n/* Generated: metrics of the ${fam} SDF atlas (font_${fam}.wad). */\nmodule.exports = ${f.data as string};\n`,
      );
    } else if (imagesByPath.has(f.path)) {
      writeFileSync(join(APP, imagesByPath.get(f.path)!), f.data as Uint8Array);
      written.add(imagesByPath.get(f.path)!);
    }
  }
  index.push({ id: c.id, name: c.name, module, palettes: Object.keys(c.palettes) });
  console.log(
    `OK   ${file} → ${APP}/${module}.js (${c.layers} layers, ${result.report.warnings.length} warnings)`,
  );
}

// A theme module or picture of a theme the app no longer carries (font_*.wad are the fonts').
if (!failed) {
  for (const name of readdirSync(APP)) {
    const generated = /^theme_.*\.js$/.test(name) || (/\.wad$/.test(name) && !/^font_/.test(name));
    if (generated && !written.has(name)) {
      unlinkSync(join(APP, name));
      console.log(`gone ${APP}/${name}`);
    }
  }
}

writeFileSync(
  join(APP, 'themes_index.js'),
  `'use strict';\n/* Generated by tools/build/build-mgu-themes.ts. Do not edit. */\nmodule.exports = ${JSON.stringify({ themes: index, fonts: [...fonts] }, null, 2)};\n`,
);

// Every shader the compiler can emit. Themes installed from a USB stick carry no
// GLSL; the app takes their shaders from here by name.
writeFileSync(
  join(APP, 'shaders.js'),
  `'use strict';
/* Generated by tools/build/build-mgu-themes.ts. Do not edit. */
module.exports = ${JSON.stringify(SHADERS, null, 2)};
`,
);

// Refresh the theme and palette choices in app.json.
const appJsonPath = join(APP, 'app.json');
if (existsSync(appJsonPath)) {
  const app = JSON.parse(readFileSync(appJsonPath, 'utf8')) as {
    settings: Array<{ key: string; options?: string[][]; default?: string }>;
  };
  const themeSetting = app.settings.find((s) => s.key === 'clusterTheme');
  if (themeSetting) {
    themeSetting.options = index.map((t) => [t.id, t.name]);
    themeSetting.default = index.some((t) => t.id === DEFAULT_THEME)
      ? DEFAULT_THEME
      : (index[0]?.id ?? '');
  }
  const paletteSetting = app.settings.find((s) => s.key === 'palette');
  if (paletteSetting) {
    const ids = [...new Set(index.flatMap((t) => t.palettes))];
    paletteSetting.options = [
      ['auto', 'Automatic (driving mode)'],
      ...ids.map((p) => [p, `Palette: ${p}`]),
    ];
  }
  writeFileSync(appJsonPath, JSON.stringify(app, null, 2) + '\n');
}

if (failed) process.exitCode = 1;
